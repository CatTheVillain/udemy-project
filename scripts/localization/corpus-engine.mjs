async function sourceFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map(async (entry) =>
      entry.isDirectory()
        ? sourceFiles(join(directory, entry.name))
        : ['.ts', '.tsx', '.js', '.jsx'].includes(extname(entry.name))
          ? [join(directory, entry.name)]
          : [],
    ),
  );
  return nested.flat();
}

function closedFunctionName(node) {
  for (let current = node; current; current = current.parent) {
    if (!ts.isFunctionLike(current)) continue;
    if (current.name && ts.isIdentifier(current.name)) return current.name.text;
    if (current.parent && ts.isVariableDeclaration(current.parent))
      return current.parent.name.getText();
    if (current.parent && ts.isPropertyAssignment(current.parent))
      return current.parent.name.getText();
  }
  return '<module>';
}

function closedOwnFunctionName(node) {
  if (!ts.isFunctionLike(node)) return undefined;
  if (node.name && ts.isIdentifier(node.name)) return node.name.text;
  if (node.parent && ts.isVariableDeclaration(node.parent)) return node.parent.name.getText();
  if (node.parent && ts.isPropertyAssignment(node.parent)) return node.parent.name.getText();
  return undefined;
}

function closedBindingContains(name, bindingName) {
  if (ts.isIdentifier(name)) return name.text === bindingName;
  return name.elements.some(
    (element) => ts.isBindingElement(element) && closedBindingContains(element.name, bindingName),
  );
}

function closedBindingIdentifier(name, bindingName) {
  if (ts.isIdentifier(name)) return name.text === bindingName ? name : undefined;
  for (const element of name.elements) {
    if (!ts.isBindingElement(element)) continue;
    const identifier = closedBindingIdentifier(element.name, bindingName);
    if (identifier) return identifier;
  }
  return undefined;
}

function closedBoundaryIdentity(sourcePath, functionName, bindingName) {
  return `${sourcePath}|${functionName}|${bindingName}`;
}

function closedConsumerIdentity(sourcePath, functionName, argument, occurrence) {
  return `${sourcePath}|${functionName}|${argument}|${occurrence}`;
}

function closedDependencyIdentity(sourcePath, functionName, hookName, bindingName) {
  return `${sourcePath}|${functionName}|${hookName}|${bindingName}`;
}

function closedConsumerSourceFingerprint(sourcePath, source) {
  return digest({
    version: CONSUMER_SOURCE_FINGERPRINT_VERSION,
    sourcePath,
    source: source.replace(/\r\n?/g, '\n'),
  });
}

export function consumerSourceFingerprint(sourcePath, source) {
  if (!validConsumerSourcePath(sourcePath))
    throw new Error('consumer source path must be a normalized relative source path');
  if (typeof source !== 'string') throw new Error('consumer source must be text');
  return closedConsumerSourceFingerprint(sourcePath, source);
}

export function rebindTranslatorWrapper(corpus, { sourcePath, functionName, bindingName, source }) {
  if (!nonEmptyString(functionName) || !nonEmptyString(bindingName))
    throw new Error('consumer function and binding names must be non-empty text');
  const wrappers = corpus?.consumerGrammar?.translatorWrappers;
  if (!Array.isArray(wrappers)) throw new Error('consumer grammar has no translator wrappers');
  const matches = wrappers.filter(
    (wrapper) =>
      wrapper?.sourcePath === sourcePath &&
      wrapper?.functionName === functionName &&
      wrapper?.bindingName === bindingName,
  );
  if (matches.length !== 1)
    throw new Error('consumer rebinding requires exactly one existing translator wrapper');
  const sourceFingerprint = consumerSourceFingerprint(sourcePath, source);
  if (matches[0].sourceFingerprint === sourceFingerprint)
    return { corpus, rebound: false, sourceFingerprint };
  const next = structuredClone(corpus);
  const nextWrapper = next.consumerGrammar.translatorWrappers.find(
    (wrapper) =>
      wrapper.sourcePath === sourcePath &&
      wrapper.functionName === functionName &&
      wrapper.bindingName === bindingName,
  );
  if (!nextWrapper) throw new Error('consumer rebinding lost the selected translator wrapper');
  nextWrapper.sourceFingerprint = sourceFingerprint;
  return { corpus: next, rebound: true, sourceFingerprint };
}

export function rebindConsumerSource(corpus, { sourcePath, source }) {
  const sourceFingerprint = consumerSourceFingerprint(sourcePath, source);
  const grammar = corpus?.consumerGrammar;
  const categories = [
    grammar?.translatorWrappers,
    grammar?.translatorForwarders,
    grammar?.translatorDependencies,
    ...(grammar?.dynamicKeyFamilies ?? []).map((family) => family?.consumers),
  ];
  const matches = categories.flatMap((entries) =>
    Array.isArray(entries) ? entries.filter((entry) => entry?.sourcePath === sourcePath) : [],
  );
  if (matches.length === 0)
    throw new Error('consumer source rebinding requires at least one existing grammar entry');
  if (matches.every((entry) => entry.sourceFingerprint === sourceFingerprint))
    return { corpus, rebound: false, sourceFingerprint, updatedEntries: matches.length };
  const next = structuredClone(corpus);
  const nextGrammar = next.consumerGrammar;
  const nextCategories = [
    nextGrammar.translatorWrappers,
    nextGrammar.translatorForwarders,
    nextGrammar.translatorDependencies,
    ...nextGrammar.dynamicKeyFamilies.map((family) => family.consumers),
  ];
  const updatedEntries = nextCategories.flatMap((entries) =>
    entries.filter((entry) => entry.sourcePath === sourcePath),
  );
  if (updatedEntries.length !== matches.length)
    throw new Error('consumer source rebinding lost selected grammar entries');
  for (const entry of updatedEntries) entry.sourceFingerprint = sourceFingerprint;
  return { corpus: next, rebound: true, sourceFingerprint, updatedEntries: updatedEntries.length };
}

function closedJsxTag(node) {
  const opening = node.parent?.parent?.parent?.parent;
  if (opening && (ts.isJsxOpeningElement(opening) || ts.isJsxSelfClosingElement(opening)))
    return opening.tagName;
  return undefined;
}

function closedDependencyMetadata(identifier, context) {
  const array = identifier.parent;
  if (
    !ts.isArrayLiteralExpression(array) ||
    array.elements.some((element) => !ts.isIdentifier(element))
  )
    return false;
  const call = array.parent;
  if (!ts.isCallExpression(call) || call.arguments[1] !== array) return false;
  const hookName = context.reactHookName(call.expression);
  if (!hookName) return false;
  const identity = closedDependencyIdentity(
    context.sourcePath,
    closedFunctionName(identifier),
    hookName,
    identifier.text,
  );
  const dependency = context.dependencies.get(identity);
  if (!dependency || dependency.sourceFingerprint !== context.sourceFingerprint) return false;
  context.usedDependencies.add(identity);
  return true;
}

function closedDeclarationIdentifier(identifier) {
  const parent = identifier.parent;
  return (
    (ts.isBindingElement(parent) &&
      (parent.name === identifier || parent.propertyName === identifier)) ||
    (ts.isParameter(parent) && parent.name === identifier) ||
    (ts.isPropertySignature(parent) && parent.name === identifier) ||
    (ts.isJsxAttribute(parent) && parent.name === identifier) ||
    (ts.isImportSpecifier(parent) &&
      (parent.name === identifier || parent.propertyName === identifier))
  );
}

function closedNodeWithin(node, owners) {
  for (let current = node; current; current = current.parent) if (owners.has(current)) return true;
  return false;
}

function closedUnitLookup(corpus) {
  const namespaced = new Map();
  const bare = new Map();
  for (const unit of corpus.units ?? []) {
    namespaced.set(`${unit.namespace}:${unit.key}`, unit);
    const owners = bare.get(unit.key) ?? [];
    owners.push(unit);
    bare.set(unit.key, owners);
  }
  const baseline = new Set();
  for (const [namespace, entries] of Object.entries(corpus.baselineResources?.en ?? {}))
    for (const key of Object.keys(entries ?? {})) baseline.add(`${namespace}:${key}`);
  return { namespaced, bare, baseline };
}

function closedSourceGraph(corpus, contents, sourceRoot) {
  const grammar = corpus.consumerGrammar;
  if (!grammar || grammar.version !== 1)
    return {
      consumers: new Map(),
      violations: ['localization consumer grammar violation: missing canonical consumer grammar'],
    };
  const wrappers = new Map(
    (grammar.translatorWrappers ?? []).map((boundary) => [
      closedBoundaryIdentity(boundary.sourcePath, boundary.functionName, boundary.bindingName),
      boundary,
    ]),
  );
  const forwarders = new Map(
    (grammar.translatorForwarders ?? []).map((boundary) => [
      closedBoundaryIdentity(boundary.sourcePath, boundary.functionName, boundary.bindingName),
      boundary,
    ]),
  );
  const boundaries = new Set([...wrappers.keys(), ...forwarders.keys()]);
  const boundaryDeclarations = [...wrappers.values(), ...forwarders.values()];
  const dependencies = new Map(
    (grammar.translatorDependencies ?? []).map((dependency) => [
      closedDependencyIdentity(
        dependency.sourcePath,
        dependency.functionName,
        dependency.hookName,
        dependency.bindingName,
      ),
      dependency,
    ]),
  );
  const declaredConsumers = new Map();
  for (const family of grammar.dynamicKeyFamilies ?? [])
    for (const consumer of family.consumers ?? [])
      declaredConsumers.set(
        closedConsumerIdentity(
          consumer.sourcePath,
          consumer.functionName,
          consumer.argument,
          consumer.occurrence,
        ),
        family,
      );
  const usedBoundaries = new Set();
  const usedDependencies = new Set();
  const usedConsumers = new Set();
  const consumers = new Map();
  const violations = [];
  const { namespaced, bare, baseline } = closedUnitLookup(corpus);
  const recordUnit = (unit, file) => {
    const files = consumers.get(unit.id) ?? new Set();
    files.add(file);
    consumers.set(unit.id, files);
  };
  const program = ts.createProgram({
    rootNames: contents.map(([file]) => file),
    options: {
      allowJs: true,
      allowImportingTsExtensions: true,
      baseUrl: resolve(sourceRoot),
      checkJs: false,
      jsx: ts.JsxEmit.Preserve,
      module: ts.ModuleKind.ESNext,
      moduleResolution: ts.ModuleResolutionKind.Bundler,
      paths: {
        '@app/*': ['app/*'],
        '@entities/*': ['entities/*'],
        '@features/*': ['features/*'],
        '@pages/*': ['pages/*'],
        '@shared/*': ['shared/*'],
        '@widgets/*': ['widgets/*'],
      },
      skipLibCheck: true,
      target: ts.ScriptTarget.Latest,
    },
  });
  const checker = program.getTypeChecker();
  for (const [file, text] of contents) {
    if (text.startsWith(GENERATED_OUTPUT_BANNER)) continue;
    const sourcePath = relative(sourceRoot, file).replaceAll('\\', '/') || basename(file);
    const sourceFile = program.getSourceFile(file);
    if (!sourceFile) {
      violations.push(
        `localization consumer grammar violation: ${sourcePath}: source cannot be bound`,
      );
      continue;
    }
    if (sourceFile.parseDiagnostics.length > 0) {
      violations.push(
        `localization consumer grammar violation: ${sourcePath}: source cannot be parsed`,
      );
      continue;
    }
    const sourceFingerprint = closedConsumerSourceFingerprint(sourcePath, text);
    const imports = [];
    const namespaceImports = [];
    const importSymbol = (node) => checker.getSymbolAtLocation(node);
    for (const statement of sourceFile.statements) {
      if (!ts.isImportDeclaration(statement) || !ts.isStringLiteral(statement.moduleSpecifier))
        continue;
      const clause = statement.importClause;
      if (clause?.namedBindings && ts.isNamedImports(clause.namedBindings)) {
        for (const element of clause.namedBindings.elements) {
          const symbol = importSymbol(element.name);
          if (!symbol) continue;
          imports.push({
            symbol,
            importedName: element.propertyName?.text ?? element.name.text,
            moduleName: statement.moduleSpecifier.text,
          });
        }
      }
      if (clause?.namedBindings && ts.isNamespaceImport(clause.namedBindings)) {
        const symbol = importSymbol(clause.namedBindings.name);
        if (symbol) namespaceImports.push({ symbol, moduleName: statement.moduleSpecifier.text });
      }
    }
    const namedImport = (node, moduleName, importedName) => {
      const symbol = checker.getSymbolAtLocation(node);
      return imports.some(
        (entry) =>
          entry.symbol === symbol &&
          entry.moduleName === moduleName &&
          entry.importedName === importedName,
      );
    };
    const namespaceImport = (node, moduleName) => {
      const symbol = checker.getSymbolAtLocation(node);
      return namespaceImports.some(
        (entry) => entry.symbol === symbol && entry.moduleName === moduleName,
      );
    };
    const importedMember = (expression, moduleName, importedName) =>
      ts.isPropertyAccessExpression(expression) &&
      ts.isIdentifier(expression.expression) &&
      namespaceImport(expression.expression, moduleName) &&
      expression.name.text === importedName;
    const hookCall = (expression) =>
      (ts.isIdentifier(expression) && namedImport(expression, 'react-i18next', 'useTranslation')) ||
      importedMember(expression, 'react-i18next', 'useTranslation');
    const reactHookName = (expression) => {
      for (const hookName of REACT_DEPENDENCY_HOOKS)
        if (
          (ts.isIdentifier(expression) && namedImport(expression, 'react', hookName)) ||
          importedMember(expression, 'react', hookName)
        )
          return hookName;
      return undefined;
    };
    const typeContainsTranslatorImport = (typeNode) => {
      let result = false;
      const visit = (node) => {
        if (result) return;
        if (
          ts.isTypeReferenceNode(node) &&
          ts.isIdentifier(node.typeName) &&
          namedImport(node.typeName, 'i18next', 'TFunction')
        )
          result = true;
        else if (
          ts.isTypeReferenceNode(node) &&
          ts.isQualifiedName(node.typeName) &&
          ts.isIdentifier(node.typeName.left) &&
          namespaceImport(node.typeName.left, 'i18next') &&
          node.typeName.right.text === 'TFunction'
        )
          result = true;
        else if (
          ts.isImportTypeNode(node) &&
          ts.isLiteralTypeNode(node.argument) &&
          ts.isStringLiteral(node.argument.literal) &&
          node.argument.literal.text === 'i18next' &&
          node.qualifier?.getText(sourceFile) === 'TFunction'
        )
          result = true;
        ts.forEachChild(node, visit);
      };
      visit(typeNode);
      if (result) return true;
      let hookReference = false;
      const findHookReference = (node) => {
        if (
          (ts.isIdentifier(node) && namedImport(node, 'react-i18next', 'useTranslation')) ||
          (ts.isQualifiedName(node) &&
            ts.isIdentifier(node.left) &&
            namespaceImport(node.left, 'react-i18next') &&
            node.right.text === 'useTranslation')
        )
          hookReference = true;
        ts.forEachChild(node, findHookReference);
      };
      findHookReference(typeNode);
      return hookReference && /\[['"]t['"]\]/.test(typeNode.getText(sourceFile));
    };
    const boundaryTypeNodes = (parameter, bindingName) => {
      if (ts.isIdentifier(parameter.name)) return parameter.type ? [parameter.type] : [];
      if (!parameter.type) return [];
      const owners = [];
      const collectMember = (declaration) => {
        const members = declaration.members ?? declaration.type?.members ?? [];
        for (const member of members)
          if (
            ts.isPropertySignature(member) &&
            member.name?.getText(sourceFile) === bindingName &&
            member.type
          )
            owners.push(member.type);
      };
      if (ts.isTypeLiteralNode(parameter.type)) collectMember(parameter.type);
      if (ts.isTypeReferenceNode(parameter.type)) {
        const symbol = checker.getSymbolAtLocation(parameter.type.typeName);
        for (const declaration of symbol?.declarations ?? []) collectMember(declaration);
      }
      return owners;
    };
    const hookTranslatorSymbols = new Set();
    const firstPass = (node) => {
      if (
        ts.isVariableDeclaration(node) &&
        ts.isObjectBindingPattern(node.name) &&
        node.initializer &&
        ts.isCallExpression(node.initializer) &&
        hookCall(node.initializer.expression)
      )
        for (const element of node.name.elements)
          if (
            ts.isBindingElement(element) &&
            (element.propertyName?.getText(sourceFile) ?? element.name.getText(sourceFile)) ===
              't' &&
            ts.isIdentifier(element.name)
          ) {
            const symbol = checker.getSymbolAtLocation(element.name);
            if (symbol) hookTranslatorSymbols.add(symbol);
          }
      ts.forEachChild(node, firstPass);
    };
    firstPass(sourceFile);
    const boundaryCandidates = [];
    const allowedTranslatorTypeNodes = new Set();
    const collectBoundaries = (node) => {
      if (ts.isFunctionLike(node)) {
        const functionName = closedOwnFunctionName(node);
        if (!functionName) {
          ts.forEachChild(node, collectBoundaries);
          return;
        }
        for (const boundary of boundaryDeclarations) {
          if (boundary.sourcePath !== sourcePath || boundary.functionName !== functionName)
            continue;
          const parameterIndex = node.parameters.findIndex((parameter) =>
            closedBindingContains(parameter.name, boundary.bindingName),
          );
          const parameter = node.parameters[parameterIndex];
          const binding = parameter
            ? closedBindingIdentifier(parameter.name, boundary.bindingName)
            : undefined;
          const symbol = binding ? checker.getSymbolAtLocation(binding) : undefined;
          const typeNodes = parameter ? boundaryTypeNodes(parameter, boundary.bindingName) : [];
          boundaryCandidates.push({
            boundary,
            node,
            parameterIndex,
            symbol,
            typeNodes,
            semanticType: typeNodes.some(typeContainsTranslatorImport),
            sourceCurrent: boundary.sourceFingerprint === sourceFingerprint,
          });
        }
      }
      ts.forEachChild(node, collectBoundaries);
    };
    collectBoundaries(sourceFile);
    const functionSymbol = (node) => {
      if (node.name && ts.isIdentifier(node.name)) return checker.getSymbolAtLocation(node.name);
      if (node.parent && ts.isVariableDeclaration(node.parent) && ts.isIdentifier(node.parent.name))
        return checker.getSymbolAtLocation(node.parent.name);
      return undefined;
    };
    const localBoundaryForExpression = (expression) => {
      if (!ts.isIdentifier(expression)) return undefined;
      const symbol = checker.getSymbolAtLocation(expression);
      return boundaryCandidates.find((candidate) => functionSymbol(candidate.node) === symbol);
    };
    const translatorSymbol = (node) =>
      ts.isIdentifier(node) ? checker.getSymbolAtLocation(node) : undefined;
    const compatibilityBoundaries = new Set();
    const collectCompatibility = (node) => {
      if (ts.isCallExpression(node)) {
        const candidate = localBoundaryForExpression(node.expression);
        const argument = candidate ? node.arguments[candidate.parameterIndex] : undefined;
        const symbol = argument ? translatorSymbol(argument) : undefined;
        if (candidate && symbol && hookTranslatorSymbols.has(symbol))
          compatibilityBoundaries.add(candidate);
      }
      ts.forEachChild(node, collectCompatibility);
    };
    collectCompatibility(sourceFile);
    const translatorSymbols = new Set(hookTranslatorSymbols);
    const activeBoundaryCandidates = [];
    const boundaryCandidateCounts = new Map();
    for (const candidate of boundaryCandidates) {
      const identity = closedBoundaryIdentity(
        sourcePath,
        candidate.boundary.functionName,
        candidate.boundary.bindingName,
      );
      boundaryCandidateCounts.set(identity, (boundaryCandidateCounts.get(identity) ?? 0) + 1);
    }
    for (const candidate of boundaryCandidates) {
      const identity = closedBoundaryIdentity(
        sourcePath,
        candidate.boundary.functionName,
        candidate.boundary.bindingName,
      );
      if (boundaryCandidateCounts.get(identity) !== 1) {
        for (const typeNode of candidate.typeNodes) allowedTranslatorTypeNodes.add(typeNode);
        violations.push(
          `localization consumer grammar violation: ambiguous translator boundary ${identity}`,
        );
        continue;
      }
      if (
        !candidate.sourceCurrent ||
        !candidate.symbol ||
        (!compatibilityBoundaries.has(candidate) && !candidate.boundary)
      ) {
        violations.push(
          `localization consumer grammar violation: invalid translator boundary ${identity}`,
        );
        continue;
      }
      usedBoundaries.add(identity);
      translatorSymbols.add(candidate.symbol);
      activeBoundaryCandidates.push(candidate);
      for (const typeNode of candidate.typeNodes) allowedTranslatorTypeNodes.add(typeNode);
    }
    const occurrenceCounts = new Map();
    const translatorIdentity = (identifier) => {
      const symbol = checker.getSymbolAtLocation(identifier);
      return Boolean(symbol && translatorSymbols.has(symbol));
    };
    const boundaryCallAllowed = (expression) => {
      if (!ts.isIdentifier(expression)) return false;
      const symbol = checker.getSymbolAtLocation(expression);
      const imported = imports.find((entry) => entry.symbol === symbol);
      return boundaryDeclarations.some((boundary) => {
        const local = activeBoundaryCandidates.find(
          (candidate) =>
            candidate.boundary === boundary && functionSymbol(candidate.node) === symbol,
        );
        if (local) return true;
        if (!imported || imported.importedName !== boundary.functionName) return false;
        let target;
        try {
          target =
            symbol && symbol.flags & ts.SymbolFlags.Alias
              ? checker.getAliasedSymbol(symbol)
              : symbol;
        } catch {
          return false;
        }
        const declarations = target?.declarations ?? [];
        return (
          declarations.length === 1 &&
          declarations.some((declaration) => {
            const targetPath = relative(
              sourceRoot,
              declaration.getSourceFile().fileName,
            ).replaceAll('\\', '/');
            return (
              targetPath === boundary.sourcePath &&
              closedOwnFunctionName(declaration) === boundary.functionName
            );
          })
        );
      });
    };
    const secondPass = (node) => {
      if (ts.isCallExpression(node) && hookCall(node.expression)) {
        const declaration = node.parent;
        if (!ts.isVariableDeclaration(declaration) || !ts.isObjectBindingPattern(declaration.name))
          violations.push(
            `localization consumer grammar violation: ${sourcePath}: unsupported useTranslation form`,
          );
      }
      if (
        (ts.isTypeReferenceNode(node) ||
          ts.isImportTypeNode(node) ||
          ts.isIndexedAccessTypeNode(node)) &&
        typeContainsTranslatorImport(node) &&
        !closedNodeWithin(node, allowedTranslatorTypeNodes)
      )
        violations.push(
          `localization consumer grammar violation: ${sourcePath}: unsupported translator indirection`,
        );
      if (
        ts.isCallExpression(node) &&
        ts.isIdentifier(node.expression) &&
        translatorIdentity(node.expression)
      ) {
        const argument = node.arguments[0];
        const functionName = closedFunctionName(node);
        if (!argument) {
          violations.push(
            `localization consumer grammar violation: ${sourcePath}: ${functionName}: missing localization key`,
          );
        } else if (ts.isStringLiteralLike(argument)) {
          const unit = argument.text.includes(':')
            ? namespaced.get(argument.text)
            : (bare.get(argument.text) ?? []).length === 1
              ? bare.get(argument.text)[0]
              : undefined;
          const baselineMatch = argument.text.includes(':') && baseline.has(argument.text);
          if (!unit && !baselineMatch)
            violations.push(
              `localization consumer grammar violation: ${sourcePath}: ${functionName}: unknown or ambiguous literal ${argument.text}`,
            );
          else if (unit) recordUnit(unit, file);
        } else {
          const argumentText = argument.getText(sourceFile);
          const triple = `${sourcePath}|${functionName}|${argumentText}`;
          const occurrence = (occurrenceCounts.get(triple) ?? 0) + 1;
          occurrenceCounts.set(triple, occurrence);
          const identity = closedConsumerIdentity(
            sourcePath,
            functionName,
            argumentText,
            occurrence,
          );
          const family = declaredConsumers.get(identity);
          if (!family)
            violations.push(
              `localization consumer grammar violation: ${sourcePath}: ${functionName}: undeclared dynamic argument ${argumentText}`,
            );
          else if (
            family.consumers.find(
              (consumer) =>
                closedConsumerIdentity(
                  consumer.sourcePath,
                  consumer.functionName,
                  consumer.argument,
                  consumer.occurrence,
                ) === identity,
            )?.sourceFingerprint !== sourceFingerprint
          ) {
            violations.push(
              `localization consumer grammar violation: ${sourcePath}: ${functionName}: stale dynamic consumer source revision ${argumentText}`,
            );
          } else {
            // Dynamic values are deliberately not inferred. A reviewed family declaration is
            // the complete, conservative consumer contract for this source occurrence.
            const familyUnits = (family.unitIds ?? [])
              .map((unitId) => corpus.units.find((candidate) => candidate.id === unitId))
              .filter(Boolean);
            usedConsumers.add(identity);
            for (const unit of familyUnits) recordUnit(unit, file);
          }
        }
      }
      if (ts.isIdentifier(node) && translatorIdentity(node) && !closedDeclarationIdentifier(node)) {
        const parent = node.parent;
        const isTranslatorCall = ts.isCallExpression(parent) && parent.expression === node;
        const isAllowedCallArgument =
          ts.isCallExpression(parent) &&
          parent.arguments.includes(node) &&
          boundaryCallAllowed(parent.expression);
        const jsxTag = closedJsxTag(node);
        const isAllowedJsx =
          ts.isJsxExpression(parent) &&
          parent.expression === node &&
          jsxTag !== undefined &&
          ts.isIdentifier(jsxTag) &&
          boundaryCallAllowed(jsxTag);
        if (
          !isTranslatorCall &&
          !isAllowedCallArgument &&
          !isAllowedJsx &&
          !closedDependencyMetadata(node, {
            dependencies,
            reactHookName,
            sourceFingerprint,
            sourcePath,
            usedDependencies,
          })
        )
          violations.push(
            `localization consumer grammar violation: ${sourcePath}: unsupported translator indirection`,
          );
      }
      ts.forEachChild(node, secondPass);
    };
    secondPass(sourceFile);
  }
  for (const identity of [...boundaries].sort())
    if (!usedBoundaries.has(identity))
      violations.push(
        `localization consumer grammar violation: stale translator boundary ${identity}`,
      );
  for (const identity of [...dependencies.keys()].sort())
    if (!usedDependencies.has(identity))
      violations.push(
        `localization consumer grammar violation: stale translator dependency ${identity}`,
      );
  for (const identity of [...declaredConsumers.keys()].sort())
    if (!usedConsumers.has(identity))
      violations.push(
        `localization consumer grammar violation: stale dynamic consumer ${identity}`,
      );
  return { consumers, violations: [...new Set(violations)].sort() };
}

export async function retiredConsumerViolations(corpus, sourceRoot = resolve('src')) {
  let files;
  let contents;
  try {
    files = await sourceFiles(sourceRoot);
    contents = await Promise.all(files.map(async (file) => [file, await readFile(file, 'utf8')]));
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    return [`localization consumer grammar violation: source contract cannot be read: ${reason}`];
  }
  const graph = closedSourceGraph(corpus, contents, sourceRoot);
  const violations = [...graph.violations];
  for (const unit of corpus.units.filter((candidate) => candidate.unitLifecycle === 'retired'))
    for (const file of graph.consumers.get(unit.id) ?? [])
      violations.push(`${unit.id}: retired unit has source consumer ${basename(file)}`);
  return [...new Set(violations)].sort();
}

async function atomicWrite(outputPath, output) {
  const temporary = join(dirname(outputPath), `.${basename(outputPath)}.${randomUUID()}.tmp`);
  let handle;
  try {
    handle = await open(temporary, 'w');
    await handle.writeFile(output, 'utf8');
    await handle.sync();
    await handle.close();
    handle = undefined;
    await rename(temporary, outputPath);
  } finally {
    await handle?.close().catch(() => undefined);
    await rm(temporary, { force: true }).catch(() => undefined);
  }
}

async function validatedCorpus({ registryPath, sourceRoot }) {
  const corpus = await readCorpus(registryPath);
  const schemaViolations = validateCorpus(corpus);
  if (!Array.isArray(corpus?.units)) return { corpus, violations: schemaViolations };
  return {
    corpus,
    violations: [
      ...schemaViolations,
      ...(await retiredConsumerViolations(corpus, sourceRoot)),
    ].sort(),
  };
}

export async function syncCorpus({ registryPath, outputPath, sourceRoot }) {
  const { corpus, violations } = await validatedCorpus({ registryPath, sourceRoot });
  if (violations.length) throw new Error(violations.join('\n'));
  const output = serializeGeneratedResources(corpus);
  await atomicWrite(outputPath, output);
  return output;
}
export async function checkCorpus({ registryPath, outputPath, sourceRoot }) {
  const { corpus, violations } = await validatedCorpus({ registryPath, sourceRoot });
  if (violations.length) return violations;
  try {
    return (await readFile(outputPath, 'utf8')) === serializeGeneratedResources(corpus)
      ? []
      : ['generated resources are out of date'];
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    return [`generated resources cannot be read: ${reason}`];
  }
}
