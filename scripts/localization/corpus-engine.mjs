function stable(value) {
  if (Array.isArray(value)) return value.map(stable);
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((key) => [key, stable(value[key])]),
    );
  }
  return value;
}

function digest(value) {
  return `sha256:${createHash('sha256')
    .update(JSON.stringify(stable(value)))
    .digest('hex')}`;
}

function placeholders(value, renderingContract) {
  const mode = renderingContract?.mode;
  if (!RENDERING_MODES.has(mode)) return /[{}]/.test(String(value)) ? null : [];
  const matcher =
    mode === 'i18next' ? /\{\{([A-Za-z][A-Za-z0-9_]*)\}\}/g : /\{([A-Za-z][A-Za-z0-9_]*)\}/g;
  const text = String(value);
  const names = [];
  let cursor = 0;
  for (const match of text.matchAll(matcher)) {
    if (
      text.slice(cursor, match.index).includes('{') ||
      text.slice(cursor, match.index).includes('}')
    )
      return null;
    names.push(match[1]);
    cursor = match.index + match[0].length;
  }
  if (text.slice(cursor).includes('{') || text.slice(cursor).includes('}')) return null;
  return names.sort();
}

function localePlaceholderContract(unit, locale) {
  const contract = unit.placeholdersByLocale?.[locale];
  return Array.isArray(contract) && contract.every(nonEmptyString) ? [...contract].sort() : null;
}

function same(left, right) {
  return (
    Array.isArray(left) &&
    Array.isArray(right) &&
    left.length === right.length &&
    left.every((value, index) => value === right[index])
  );
}

function sameStableValue(left, right) {
  return JSON.stringify(stable(left)) === JSON.stringify(stable(right));
}

function hasExactKeys(value, expectedKeys) {
  return (
    value &&
    typeof value === 'object' &&
    !Array.isArray(value) &&
    same(Object.keys(value).sort(), expectedKeys)
  );
}

function hasExactLocaleKeys(value) {
  return (
    value &&
    typeof value === 'object' &&
    !Array.isArray(value) &&
    same(Object.keys(value).sort(), LOCALES)
  );
}

function nonEmptyString(value) {
  return typeof value === 'string' && value.trim().length > 0;
}

