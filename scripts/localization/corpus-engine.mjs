export function applyProtectedSourceRevision(candidate, sourceRevision, newCandidate = undefined) {
  assertValidCandidateLifecycleSource(candidate, 'revise protected source for');
  const shouldStale = ['approved', 'review_requested', 'changes_requested'].includes(
    candidate.status,
  );
  if (
    newCandidate !== undefined &&
    (!nonEmptyString(newCandidate) || newCandidate === candidate.candidate)
  )
    throw new Error('draft reset requires a new non-empty candidate');
  if (newCandidate !== undefined && candidate.status !== 'draft')
    throw new Error('draft reset is allowed only for a draft candidate');
  return {
    ...clearApprovalMetadata(candidate),
    candidate: newCandidate ?? candidate.candidate,
    sourceRevision,
    status: shouldStale ? 'stale' : candidate.status,
    history: [
      ...candidate.history,
      {
        type: 'source_revision',
        previousSourceRevision: candidate.sourceRevision,
        sourceRevision,
      },
      ...(newCandidate === undefined
        ? []
        : [
            {
              type: 'draft_reset',
              previousCandidate: candidate.candidate,
              nextCandidate: newCandidate,
              sourceRevision,
            },
          ]),
      ...(shouldStale
        ? [
            {
              type: 'transition',
              from: candidate.status,
              to: 'stale',
              previousCandidate: candidate.candidate,
              nextCandidate: candidate.candidate,
              sourceRevision,
            },
          ]
        : []),
    ],
  };
}

function assertSupportedCorpusVersion(corpus) {
  if (corpus?.corpusVersion !== DRAFT_37 || corpus?.migration?.sourceVersion !== DRAFT_37)
    throw new Error(`unsupported corpus version: expected ${DRAFT_37}`);
}

export function generateResources(corpus) {
  assertSupportedCorpusVersion(corpus);
  const resources = JSON.parse(JSON.stringify(corpus.baselineResources));
  for (const unit of [...corpus.units].sort((a, b) => a.id.localeCompare(b.id))) {
    if (unit.unitLifecycle !== 'active') {
      for (const locale of LOCALES) {
        const namespace = resources[locale]?.[unit.namespace];
        if (!namespace || typeof namespace !== 'object') continue;
        removeUnitResourceShape(namespace, unit, locale);
      }
      continue;
    }
    for (const [locale, value] of [
      ['en', unit.english],
      ['ru', unit.locales.ru.candidate],
      ['uz', unit.locales.uz.candidate],
    ]) {
      const namespace = (resources[locale][unit.namespace] ??= {});
      removeUnitResourceShape(namespace, unit, locale);
      const forms = unit.pluralForms?.[locale];
      if (forms)
        for (const [suffix, plural] of Object.entries(forms))
          namespace[`${unit.key}_${suffix}`] = plural;
      else namespace[unit.key] = value;
    }
  }
  return resources;
}

function supportedPluralKeySuffixes(locale) {
  return new Set([...pluralCategories(locale), ...SUPPORTED_PLURAL_EXTRAS]);
}

function pluralKeySuffixes(unit, locale) {
  return new Set([
    ...LOCALES.flatMap(pluralCategories),
    ...SUPPORTED_PLURAL_EXTRAS,
    ...Object.keys(unit.pluralForms?.[locale] ?? {}),
    ...(HISTORIC_GENERATED_PLURAL_SUFFIXES.get(`${unit.namespace}:${unit.key}`) ?? []),
  ]);
}

function generatedShapeKeys(unit) {
  return new Set([
    unit.key,
    ...LOCALES.flatMap((locale) =>
      [...pluralKeySuffixes(unit, locale)].map((suffix) => `${unit.key}_${suffix}`),
    ),
  ]);
}

function validateGeneratedShapeCollisions(units, violations) {
  const owners = new Map();
  for (const unit of [...units]
    .filter((candidate) => candidate && typeof candidate === 'object')
    .sort((left, right) => String(left.id).localeCompare(String(right.id)))) {
    if (!nonEmptyString(unit.namespace) || !nonEmptyString(unit.key)) continue;
    for (const generatedKey of generatedShapeKeys(unit)) {
      const resourceKey = `${unit.namespace}:${generatedKey}`;
      const owner = owners.get(resourceKey);
      if (owner && owner.id !== unit.id)
        violations.push(
          `${unit.id}: namespace/key collides with generated shape of ${owner.id} (${resourceKey})`,
        );
      else owners.set(resourceKey, unit);
    }
  }
}

function removeUnitResourceShape(namespace, unit, locale) {
  delete namespace[unit.key];
  for (const suffix of pluralKeySuffixes(unit, locale)) delete namespace[`${unit.key}_${suffix}`];
}

export function serializeGeneratedResources(corpus) {
  return `${GENERATED_OUTPUT_BANNER}\nimport type { Resource } from 'i18next';\n\nexport const GENERATED_LOCALE_RESOURCES = ${JSON.stringify(generateResources(corpus), null, 2)} satisfies Resource & Readonly<Record<'en' | 'ru' | 'uz', Resource[string]>>;\n`;
}
